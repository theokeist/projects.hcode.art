export function enrichAdvancedItem(item) {
  const term = item.hanzi || item.term || '';
  const sound = item.pinyin || item.sound || '';
  const meaning = item.czech || item.meaning || '';
  const kind = item.type === 'adjective' || item.kind === 'Adjective' ? 'Adjective' : 'Conjunction';

  const characters = [];
  const seen = new Set();
  for (const ch of term) {
    if (ch >= '\u3400' && ch <= '\u9fff' && !seen.has(ch)) {
      seen.add(ch);
      const def = CHARACTER_DEFS[ch] || { sound: '', meaning: '' };
      characters.push({
        term: ch,
        sound: def.sound,
        meaning: def.meaning,
        known: false
      });
    }
  }

  let note = '';
  if (kind === 'Conjunction') {
    if (term.includes('...') || term.includes('···')) {
      note = `Párová spojka: propojuje a logicky strukturuje větné celky v souvětí (${meaning}).`;
    } else {
      note = `Spojka s významem „${meaning}“; propojuje slova nebo věty.`;
    }
  } else {
    if (characters.length === 1) {
      note = `Základní jednoslabičné přídavné jméno (${meaning}). V kladných přísudkových větách se obvykle pojí se sponou 很.`;
    } else {
      const charMeanings = characters.map(c => `${c.term} (${(c.meaning || '').split(';')[0].split(',')[0].trim()})`).join(' + ');
      note = `Dvojslabičné přídavné jméno složené ze znaků: ${charMeanings}.`;
    }
  }

  return {
    term, sound, meaning, kind, characters, note
  };
}
